from __future__ import annotations

import shutil
import subprocess
import unittest
from pathlib import Path

SCRIPT = Path(__file__).resolve().parent / "ci-annota.sh"


def annotate(log: str, *args: str) -> list[str]:
    done = subprocess.run(["bash", str(SCRIPT), *args], input=log, capture_output=True,
                          text=True, check=True, env={"PATH": "/usr/bin:/bin",
                                                      "GITHUB_WORKSPACE": "/w"})
    return [line for line in done.stdout.splitlines() if line.startswith("::error")]


@unittest.skipUnless(shutil.which("bash"), "needs bash")
class Invalid(unittest.TestCase):
    def test_invalid_case_with_a_line(self):
        lines = annotate("INVALID: tests/verifica/casi/a/b: domande.tgq, line 29: "
                         "Dimension cannot be regenerated by Tecnigrafo.\n")
        self.assertEqual(lines, [
            "::error file=tests/verifica/casi/a/b/domande.tgq,line=29,"
            "title=INVALID tests/verifica/casi/a/b::Dimension cannot be regenerated by Tecnigrafo."])

    def test_invalid_case_without_a_line(self):
        lines = annotate("INVALID: /w/tests/verifica/casi/a/c: empty line at the end\n")
        self.assertEqual(lines, ["::error title=INVALID tests/verifica/casi/a/c::empty line at the end"])

    def test_invalid_is_not_an_unrecognised_ctest_failure(self):
        log = ("INVALID: tests/verifica/casi/a/c: bad\n"
               "1/1 Test #7: verifica.a.c ......***Failed    0.10 sec\n")
        lines = annotate(log)
        self.assertEqual(len(lines), 1)
        self.assertNotIn("no diagnostic recognised", lines[0])


@unittest.skipUnless(shutil.which("bash"), "needs bash")
class Oracle(unittest.TestCase):
    LOG = ("=== Oracle case: tests/verifica/casi/a ===\n"
           "tests/verifica/casi/a/domande.tgq:9: ? entity H 1F origin\n"
           "  expected: 245,5\n"
           "  ezdxf:    0,0\n"
           "tests/verifica/casi/a/domande.tgq:10: skipped (outside oracle scope): ? x\n"
           "Oracle: 1 declared cases, 2 checked questions.\n"
           "Audit: 144 drawings, 0 failures.\n")

    def test_failing_question_on_its_line_before_the_tail(self):
        lines = annotate(self.LOG, "--coda", "Oracolo ezdxf")
        self.assertEqual(len(lines), 2)
        self.assertEqual(lines[0],
                         "::error file=tests/verifica/casi/a/domande.tgq,line=9,"
                         "title=Oracolo ezdxf::? entity H 1F origin | expected: 245,5 | ezdxf: 0,0")
        self.assertIn("Audit: 144 drawings", lines[1])

    def test_tail_alone_without_oracle_lines(self):
        lines = annotate("Traceback\nValueError: boom\n", "--coda", "Scripts (Python)")
        self.assertEqual(len(lines), 1)
        self.assertTrue(lines[0].startswith("::error title=Scripts (Python)::"))


if __name__ == "__main__":
    unittest.main()
